-- 7546 picker dispatch. Read-only views for Dashboard Designer.
-- LAST_UPDATE_DATE / LAST_UPDATE_TIME are the last save on the load line.
-- They are not the time the pick finished.
-- Load 0 is skipped. Load 9999 is Pre-pick, not a truck.
-- Blank and ~ANY are the Any pool. The picker name is not joined:
-- MOBILE_USER_INFO lives on the common database, not this company database.
-- Counts only. No goal, no units per hour, no travel, no weight.
-- Queue days start the day Ready to Pick is turned on. The clock time is
-- saved with that day. A later save does not move either one. Putting the
-- line on another load keeps that same day and time.
-- Lines already released have no start until marked again.
-- The shipping screen creates this table and these views on open when
-- they are missing. This file is the same definition. Do not drop the
-- table. If it already exists without RELEASED_TIME, add that column.
-- If it already exists, skip CREATE TABLE and run from the drops.

CREATE TABLE GAB_7546_PICK_RELEASE (
	ORDER_NO CHAR(7) NOT NULL,
	ORDER_SUFFIX CHAR(4) NOT NULL,
	ORDER_LINE CHAR(4) NOT NULL,
	LOAD_NO INTEGER NOT NULL,
	RELEASED_DATE DATE,
	RELEASED_TIME TIME,
	PRIMARY KEY (ORDER_NO, ORDER_SUFFIX, ORDER_LINE, LOAD_NO)
);

DROP VIEW IF EXISTS V_GAB_7546_PICK_DAY;
DROP VIEW IF EXISTS V_GAB_7546_LOAD_DISPATCH;
DROP VIEW IF EXISTS V_GAB_7546_PICK_NOW;
DROP VIEW IF EXISTS V_GAB_7546_PICK_LINE;

CREATE VIEW V_GAB_7546_PICK_LINE AS
SELECT
	CASE
		WHEN RTRIM(LP.ASSIGNED_TO) = '' OR RTRIM(LP.ASSIGNED_TO) = '~ANY' THEN 'Any'
		ELSE RTRIM(LP.ASSIGNED_TO)
	END AS PICKER,
	RTRIM(LP.ASSIGNED_TO) AS ASSIGNED_TO,
	LP.LOAD_NO,
	CASE WHEN LP.LOAD_NO = 9999 THEN 'Pre-pick' ELSE 'Load' END AS LOAD_KIND,
	LP.ORDER_NO,
	LP.ORDER_SUFFIX,
	LP.ORDER_LINE,
	OH.CUSTOMER_PO,
	LP.PICKED,
	LP.SHIPPED,
	LP.PICK_BY_DATE,
	LP.SHIP_DATE,
	LP.MODIFIED_DATE AS LAST_UPDATE_DATE,
	LP.MODIFIED_TIME AS LAST_UPDATE_TIME,
	CASE
		WHEN LP.PCKLST_DISP_FLAG = 1 AND LP.PICKED <> 1 AND LP.SHIPPED <> 1 AND R.RELEASED_DATE > '1900-01-01'
		THEN DATEDIFF(day, R.RELEASED_DATE, CURDATE())
		ELSE NULL
	END AS QUEUE_DAYS,
	CASE
		WHEN LP.PCKLST_DISP_FLAG = 1 AND LP.PICKED <> 1 AND LP.SHIPPED <> 1 AND R.RELEASED_DATE > '1900-01-01' AND R.RELEASED_TIME IS NOT NULL
		THEN CONCAT(CONCAT(CONVERT(R.RELEASED_DATE, SQL_CHAR), ' '), CONVERT(R.RELEASED_TIME, SQL_CHAR))
		ELSE NULL
	END AS RELEASED_AT
FROM LOAD_PLAN LP
LEFT JOIN GAB_7546_PICK_RELEASE R
	ON R.ORDER_NO = LP.ORDER_NO
	AND R.ORDER_SUFFIX = LP.ORDER_SUFFIX
	AND R.ORDER_LINE = LP.ORDER_LINE
	AND R.LOAD_NO = LP.LOAD_NO
LEFT JOIN V_ORDER_HEADER OH
	ON OH.ORDER_NO = LP.ORDER_NO
	AND OH.ORDER_SUFFIX = LP.ORDER_SUFFIX
	AND OH.RECORD_NO = '  A'
WHERE LP.LOAD_NO > 0;

CREATE VIEW V_GAB_7546_PICK_NOW AS
SELECT
	PICKER,
	SUM(CASE WHEN PICKED <> 1 THEN 1 ELSE 0 END) AS LINES_OPEN,
	SUM(CASE WHEN PICKED = 1 THEN 1 ELSE 0 END) AS LINES_PICKED_NOT_SHIPPED,
	COUNT(DISTINCT LOAD_NO) AS LOADS,
	MIN(CASE WHEN PICKED <> 1 AND PICK_BY_DATE > '1900-01-01' THEN PICK_BY_DATE ELSE NULL END) AS OLDEST_PICK_BY_STILL_OPEN,
	MAX(QUEUE_DAYS) AS LONGEST_QUEUE_DAYS,
	MIN(RELEASED_AT) AS EARLIEST_RELEASE
FROM V_GAB_7546_PICK_LINE
WHERE SHIPPED <> 1
GROUP BY PICKER;

CREATE VIEW V_GAB_7546_LOAD_DISPATCH AS
SELECT
	LOAD_NO,
	LOAD_KIND,
	SUM(CASE WHEN PICKED <> 1 THEN 1 ELSE 0 END) AS LINES_OPEN,
	SUM(CASE WHEN PICKED = 1 THEN 1 ELSE 0 END) AS LINES_PICKED,
	MIN(CASE WHEN SHIP_DATE > '1900-01-01' THEN SHIP_DATE ELSE NULL END) AS SHIP_DATE,
	MIN(CASE WHEN PICK_BY_DATE > '1900-01-01' THEN PICK_BY_DATE ELSE NULL END) AS OLDEST_PICK_BY,
	MAX(CASE WHEN PICKER = 'Any' THEN 1 ELSE 0 END) AS ANY_STILL_ASSIGNED,
	MAX(QUEUE_DAYS) AS LONGEST_QUEUE_DAYS,
	MIN(RELEASED_AT) AS EARLIEST_RELEASE
FROM V_GAB_7546_PICK_LINE
WHERE SHIPPED <> 1
GROUP BY LOAD_NO, LOAD_KIND;

CREATE VIEW V_GAB_7546_PICK_DAY AS
SELECT
	PICKER,
	SUM(CASE WHEN PICKED = 1 AND LAST_UPDATE_DATE = CURDATE() THEN 1 ELSE 0 END) AS LINES_PICKED_TODAY,
	COUNT(DISTINCT CASE WHEN PICKED = 1 AND LAST_UPDATE_DATE = CURDATE() THEN ORDER_NO ELSE NULL END) AS ORDERS_TOUCHED_TODAY,
	COUNT(DISTINCT CASE WHEN PICKED = 1 AND LAST_UPDATE_DATE = CURDATE() THEN LOAD_NO ELSE NULL END) AS LOADS_TOUCHED_TODAY,
	SUM(CASE WHEN SHIPPED = 1 AND LAST_UPDATE_DATE = CURDATE() THEN 1 ELSE 0 END) AS LINES_SHIPPED_TODAY,
	SUM(CASE WHEN SHIPPED <> 1 AND PICKED <> 1 THEN 1 ELSE 0 END) AS LINES_STILL_OPEN,
	SUM(CASE WHEN SHIPPED <> 1 AND PICKED <> 1 AND PICK_BY_DATE > '1900-01-01' AND PICK_BY_DATE < CURDATE() THEN 1 ELSE 0 END) AS LINES_OPEN_PAST_PICK_BY
FROM V_GAB_7546_PICK_LINE
GROUP BY PICKER;
